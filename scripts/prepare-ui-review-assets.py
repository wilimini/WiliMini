#!/usr/bin/env python3
"""Build native PSP review assets from a local Wiliwili checkout. Requires Pillow, CairoSVG."""
import argparse, hashlib, io, json, shutil
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import cairosvg
p=argparse.ArgumentParser(); p.add_argument('wiliwili',type=Path); a=p.parse_args()
root=Path(__file__).resolve().parents[1]; out=root/'client/assets/wiliwili'; out.mkdir(parents=True,exist_ok=True)
font=a.wiliwili/'resources/font/switch_font.ttf'
strings=(root/'client/ui_review.inc').read_text(); chars=sorted(set(strings)|set(chr(i) for i in range(32,127)))
alpha=[]; glyphs=[]
for size in (12,14,16):
 f=ImageFont.truetype(str(font),size)
 for c in chars:
  if ord(c)<32:continue
  im=Image.new('L',(size+2,size+5));ImageDraw.Draw(im).text((0,size),c,font=f,fill=255,anchor='ls')
  glyphs.append((ord(c),size,round(f.getlength(c)),len(alpha)));alpha.extend((v+8)//17 for v in im.getdata())
# 4-bit coverage, two pixels per byte, decoded directly into the framebuffer.
packed=[alpha[i]|((alpha[i+1] if i+1<len(alpha) else 0)<<4) for i in range(0,len(alpha),2)]
items=[('pictures/22_open.png',(80,100)),('pictures/33_open.png',(80,100)),('pictures/default_avatar.png',(42,42))]
items += [('svg/ico-'+n+'.svg',(22,22)) for n in ('home','dynamic','mine','inbox','setting')]
images=[]; pixels=[]; manifest=[]
for rel,dim in items:
 src=a.wiliwili/'resources'/rel
 im=Image.open(io.BytesIO(cairosvg.svg2png(url=str(src)))) if src.suffix=='.svg' else Image.open(src)
 im=im.convert('RGBA');im.thumbnail(dim,Image.Resampling.LANCZOS)
 images.append(im);manifest.append({'source':'resources/'+rel,'sha256':hashlib.sha256(src.read_bytes()).hexdigest(),'original_bytes':src.stat().st_size,'size':im.size})
# Original, synthetic cover artwork; no third-party video thumbnails redistributed.
for style in range(2):
 im=Image.new('RGBA',(190,107));d=ImageDraw.Draw(im)
 for y in range(107):d.line((0,y,190,y),fill=(35+y//3,83+y//3,112+y//2) if not style else (174+y//3,119+y//3,117+y//3))
 d.ellipse((130,14,155,39),fill='#ffdfa3');d.polygon([(0,94),(40,32),(87,91),(135,52),(190,103)],fill='#345769' if not style else '#6e6e83');d.polygon([(0,107),(61,65),(110,107),(169,71),(190,107)],fill='#203f53' if not style else '#4e536a')
 d.line((78,107,105,85,97,75),fill='#f8c3ad',width=3)
 images.append(im);manifest.append({'source':'original synthetic landscape '+str(style),'original_bytes':0,'size':im.size})
for i,im in enumerate(images):
 im.save(out/f'{i:02}.png',optimize=True)
 data=[((a//17)<<12)|((r//17)<<8)|((g//17)<<4)|(b//17) for r,g,b,a in im.getdata()]
 off=len(pixels);last=data[0];run=0
 for v in data:
  if v==last and run<65535:run+=1
  else:pixels.extend((run,last));last=v;run=1
 pixels.extend((run,last));manifest[i]['rle_bytes']=(len(pixels)-off)*2;manifest[i]['offset']=off;manifest[i]['count']=len(pixels)-off
with (out/'generated.hpp').open('w') as f:
 f.write('// Generated by scripts/prepare-ui-review-assets.py. See MANIFEST.json and licenses.\n#pragma once\n')
 f.write('struct ReviewGlyph {unsigned cp; unsigned short size,advance; unsigned offset;};\nstruct ReviewImage {unsigned w,h,offset,count;};\n')
 for typ,name,data in [('unsigned char','reviewAlpha',packed),('unsigned short','reviewPixels',pixels)]:
  f.write(f'static const {typ} {name}[]={{\n');
  for i in range(0,len(data),40):f.write(','.join(map(str,data[i:i+40]))+',\n')
  f.write('};\n')
 f.write('static const ReviewGlyph reviewGlyphs[]={'+','.join('{'+','.join(map(str,g))+'}' for g in glyphs)+'};\n')
 f.write('static const ReviewImage reviewImages[]={'+','.join('{'+','.join(map(str,(*m['size'],m['offset'],m['count'])))+'}' for m in manifest)+'};\n')
shutil.copyfile(a.wiliwili/'resources/font/LICENSE.txt',out/'FONT-LICENSE.txt');shutil.copyfile(a.wiliwili/'LICENSE',out/'WILIWILI-LICENSE.txt')
report={'upstream_commit':'88e5876bea9502d06f46a8656e3530684d3aaf7d','font_source':'resources/font/switch_font.ttf','font_sha256':hashlib.sha256(font.read_bytes()).hexdigest(),'font_source_bytes':font.stat().st_size,'font_coverage_bytes':len(packed),'glyph_count':len(glyphs),'images':manifest,'note':'Wiliwili assets retain upstream GPL license; Source font SIL OFL. Landscape covers are original fixtures. Subset covers review text only.'}
(out/'MANIFEST.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
print('Font coverage:',len(packed),'bytes; image RLE:',len(pixels)*2,'bytes')

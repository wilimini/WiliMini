#!/usr/bin/env python3
"""Rasterize the pinned wiliwili SVGs; requires rsvg-convert and ImageMagick."""
from pathlib import Path
import hashlib
import json
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
names = ['bpx-svg-sprite-play.svg', 'bpx-svg-sprite-pause.svg',
         'bpx-svg-sprite-setting.svg', 'widget-video-danmaku.svg']
rows, sources = [], []
for name in names:
    source = root / 'assets/player' / name
    with tempfile.TemporaryDirectory() as directory:
        png = Path(directory) / 'icon.png'
        subprocess.run(['rsvg-convert', '-w', '20', '-h', '20', '-o', str(png), str(source)], check=True)
        alpha = subprocess.check_output(['magick', str(png), '-alpha', 'extract', '-depth', '8', 'gray:-'])
    assert len(alpha) == 400
    rows.append('    {' + ','.join(str(x) for x in alpha) + '}')
    sources.append(dict(path='resources/svg/'+name, sha256=hashlib.sha256(source.read_bytes()).hexdigest()))
(root / 'client/assets/player_icons.generated.hpp').write_text(
    '// Generated by scripts/generate-player-icons.py. Do not edit.\n#pragma once\n#include <cstdint>\n'
    'namespace player_icons {\ninline constexpr uint8_t alpha[4][400] = {\n' + ',\n'.join(rows) + '\n};\n}\n')
(root / 'assets/player/MANIFEST.json').write_text(json.dumps(dict(
    upstream='https://github.com/xfangfang/wiliwili', commit='88e5876bea9502d06f46a8656e3530684d3aaf7d',
    license='GPL-3.0; see client/assets/wiliwili/WILIWILI-LICENSE.txt', sources=sources), indent=2)+'\n')
